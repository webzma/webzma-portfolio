export interface ProjectEntry {
	/* Stable, language-independent key. It is the /work/<slug> URL and the
	   join between the two locales, so it never gets translated. */
	slug: string
	name: string
	href: string
	host: string
	/* Facts, not adjectives. `status` is the one the reader cares about: a
	   live site and a parked one are different claims. */
	status: 'live' | 'archived'
	year?: string
	role?: string
	description: string
	stack: string
	/* Optional screenshot for the case study, as a path under public/ —
	   e.g. '/images/zellarotile.png'. Drop a file in and it appears. */
	shot?: string
	/* Present ⇒ the row links inward to a case study and the live site moves
	   to the end of that page. Absent ⇒ the row links straight out. */
	study?: {
		brief: string
		decisions: string[]
		outcome: string
	}
}

